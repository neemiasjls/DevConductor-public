// Testa as interações: lupa seguindo o mouse, clique que inverte, botão magnético e toque no celular.
import puppeteer from 'puppeteer-core'
import fs from 'node:fs'
const saida = process.argv[2] || 'revisao/interacao'
fs.mkdirSync(saida, { recursive: true })
const esperar = (ms) => new Promise((r) => setTimeout(r, ms))
const nav = await puppeteer.launch({ executablePath: 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe', headless: true })
const p = await nav.newPage()
await p.setViewport({ width: 1440, height: 900 })
await p.goto('http://localhost:5183/', { waitUntil: 'networkidle0' })
const rolarAte = async (sel, dy = 0) => { await p.evaluate((sel, dy) => scrollTo(0, document.querySelector(sel).getBoundingClientRect().top + scrollY + dy), sel, dy); await esperar(1500) }
await rolarAte('#trabalho', 60)
const fig = await p.evaluate(() => { const r = document.querySelector('[data-figura]').getBoundingClientRect(); return { x: r.left, y: r.top, w: r.width, h: r.height } })
const lupaPos = () => p.evaluate(() => { const r = document.querySelector('[data-lupa]').getBoundingClientRect(); return [Math.round(r.left + r.width / 2), Math.round(r.top + r.height / 2)] })
const estacionada = await lupaPos()
await p.mouse.move(fig.x + fig.w * 0.2, fig.y + fig.h * 0.6, { steps: 8 })
await esperar(700)
const seguindo = await lupaPos()
await p.screenshot({ path: `${saida}/lupa-mouse.jpg`, type: 'jpeg', quality: 75 })
await p.mouse.click(fig.x + fig.w * 0.7, fig.y + fig.h * 0.3)
await esperar(700)
const invertida = await p.evaluate(() => document.querySelector('[data-figura]').getAttribute('aria-pressed'))
await p.screenshot({ path: `${saida}/clique-inverte.jpg`, type: 'jpeg', quality: 75 })
await p.mouse.move(5, 5)
await esperar(800)
const voltou = await lupaPos()
await rolarAte('#contato', 0)
const b = await p.evaluate(() => { const r = document.querySelector('[data-magnetico]').getBoundingClientRect(); return { x: r.left + r.width / 2, y: r.top + r.height / 2, w: r.width } })
await p.mouse.move(b.x + b.w * 0.45, b.y - 60, { steps: 6 })
await esperar(700)
const desloc = await p.evaluate(() => { const m = new DOMMatrix(getComputedStyle(document.querySelector('[data-magnetico]')).transform); return [Math.round(m.e), Math.round(m.f)] })
await p.screenshot({ path: `${saida}/magnetico.jpg`, type: 'jpeg', quality: 75 })
// celular: toque inverte
const c = await nav.newPage()
await c.setViewport({ width: 390, height: 844, isMobile: true, hasTouch: true })
await c.goto('http://localhost:5183/', { waitUntil: 'networkidle0' })
await c.evaluate(() => scrollTo(0, document.querySelector('[data-figura]').getBoundingClientRect().top + scrollY - 100)); await esperar(1500)
await c.tap('[data-figura]'); await esperar(700)
const toque = await c.evaluate(() => document.querySelector('[data-figura]').getAttribute('aria-pressed'))
await c.screenshot({ path: `${saida}/toque-inverte.jpg`, type: 'jpeg', quality: 75 })
console.log(JSON.stringify({ fig: [Math.round(fig.x), Math.round(fig.y), Math.round(fig.w)], estacionada, seguindo, alvoMouse: [Math.round(fig.x + fig.w * 0.2), Math.round(fig.y + fig.h * 0.6)], invertida, voltou, magnetico: desloc, toque }))
await nav.close()
